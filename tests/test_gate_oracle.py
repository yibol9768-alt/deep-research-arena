def test_g2_shell_scores_zero_on_every_axis(gates_key_paths, gates_registry):
    """A report with no checkable content earns 0 on reach, pof, fact,
    completeness, spec AND composed truth, on every task. Any nonzero is a
    laundering hole."""
    empty_stats = ds.build_page_stats({})
    bad = []
    for path in gates_key_paths:
        ak = AnswerKey.load(path)
        s = ds.score_report(SHELL_REPORT, ak, cache={}, registry=gates_registry,
                            page_stats=empty_stats)
        axes = {
            "reach": s.reach, "pof": s.proof_of_fetch,
            "fact": s.fact_support, "completeness": s.completeness,
            "spec": s.spec, "truth": s.truth,
        }
        nonzero = {k: v for k, v in axes.items() if v != 0.0}
        if nonzero:
            bad.append(f"{ak.task_id}: nonzero axes {nonzero}")
    assert not bad, "G2 shell earned score on:\n" + "\n".join(bad)


def test_g2_shell_zero_is_observed_not_withheld(gates_key_paths, gates_registry):
    """The shell's zeros must be OBSERVED zeros (scored, with detail), not the
    product of a withhold path: completeness reports pool>0 with covered==0 and
    fact reports no_checkable_claims. Guards the 'withhold never scores 0 /
    0 always means observed-and-bad' invariant from the G2 side."""
    bad = []
    for path in gates_key_paths:
        ak = AnswerKey.load(path)
        comp, cd = ds.score_completeness(SHELL_REPORT, ak, cache={},
                                         registry=gates_registry)
        fact, fd = ds.score_fact_support(SHELL_REPORT, ak)
        if not (comp == 0.0 and cd.get("pool", 0) > 0 and cd.get("covered") == 0):
            bad.append(f"{ak.task_id}: completeness detail not an observed zero: "
                       f"comp={comp} pool={cd.get('pool')} covered={cd.get('covered')}")
        if not (fact == 0.0 and fd.get("reason") == "no_checkable_claims"
                and fd.get("fact_active") is False):
            bad.append(f"{ak.task_id}: fact detail not an observed zero: "
                       f"fact={fact} reason={fd.get('reason')}")
    assert not bad, "G2 zero-semantics broken on:\n" + "\n".join(bad)
