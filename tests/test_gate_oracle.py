"""Gates G1 (oracle tops out) + G2 (shell zeroes) over all 100 answer keys.

G1: a report that does exactly what the answer key demands (the oracle report
mechanically generated by ``src/eval/oracle_report.py``) must saturate every
axis the observable world allows:

    reach = 1.0, fact > 0, completeness == the achievable ceiling, EXACTLY.

"Achievable ceiling" and not the literal 1.0 of GOAL_GATES_V1 for the STRICT
completeness score, because the strict denominator still carries slots no report
can fill on the current fixture (the forum virtual slot, uncached concepts). The
DIAGNOSTIC completeness score (ruling #2) now reaches literal 1.0 on all 100
tasks, since the three blockers that used to hold it below are each resolved:

  * the forum virtual slot: no forum thread page exists in any page cache
    fixture, so it is WITHHELD from the diagnostic denominator (ruling #2),
    not scored as an earned miss;
  * short-subject concepts ("Tea"): the short-topic deadlock fix (ruling #5)
    credits them by word-boundary matching, so they are coverable;
  * title-only stub pages in the capture ("Input lag", dr_cross_deep_0038):
    the page is cached but its whole body is shorter than the scorer's 400-char
    containment window, so no report can ground it. Per docs/SPEC_DECISIONS.md
    '车道追加条目' (分母只含"存在某报告能覆盖"的槽位) such a stub slot is now EXCISED
    from the vital pool at pool-construction time and recorded in the pool
    manifest (``excluded_slots``), so it leaves the denominator entirely instead
    of pinning completeness below 1.0.

The EXACT-equality assertion against the generator's by-construction plan is
the real gate: the scorer must credit precisely the nuggets the oracle made
coverable, no more (no phantom credit) and no fewer (no silent zeroing).

G2: a shell report with no checkable content must score 0 on every axis and
on composed truth, for every task.

Marked ``gates`` (deselected by default; run via scripts/run_gates.py).
Deterministic: committed answer keys + committed cache fixture; no network,
no clock, no randomness.
"""

from __future__ import annotations

import os

import pytest

import src.eval.decidable_scorer as ds
from src.eval.answer_key import AnswerKey
from src.eval.oracle_report import CONCEPT_CACHE_REL, build_oracle_report

pytestmark = pytest.mark.gates

SHELL_REPORT = (
    "# Report\n\n"
    "This report has nothing checkable to say about anything at all. It cites "
    "no sources, names no products, and asserts no prices, ratings or facts."
)

NO_CACHE_SKIP = (
    f"concept page cache fixture absent ({CONCEPT_CACHE_REL}): the concept "
    "share of completeness is unverifiable on this checkout and is skipped "
    "EXPLICITLY; structured coverage, fact and reach are still asserted."
)


@pytest.fixture(scope="module")
def oracle_runs(gates_key_paths, gates_registry, gates_concept_cache,
                gates_page_stats):
    """Score the oracle report once per task; every G1 test asserts over this."""
    cache = gates_concept_cache or {}
    runs = []
    for path in gates_key_paths:
        ak = AnswerKey.load(path)
        rep = build_oracle_report(ak, cache=cache, registry=gates_registry)
        generic = ds.build_generic_tokens(ak)
        comp, cd = ds.score_completeness(
            rep.markdown, ak, generic=generic, cache=cache,
            page_stats=gates_page_stats, registry=gates_registry)
        # Ruling #6 (docs/SPEC_DECISIONS.md): the diagnostic cache_policy score
        # (ruling #2) is what the literal-1.0 attempt is measured against -- it
        # withholds the cache-blind forum slot instead of zeroing it.
        comp_diag, cd_diag = ds.score_completeness(
            rep.markdown, ak, generic=generic, cache=cache,
            page_stats=gates_page_stats, registry=gates_registry,
            cache_policy="diagnostic")
        fact, fd = ds.score_fact_support(rep.markdown, ak, generic=generic)
        reach, rd = ds.score_reachability(
            rep.cited_urls, cache, registry=gates_registry)
        runs.append({
            "tid": ak.task_id, "plan": rep.plan,
            "comp": comp, "cd": cd, "comp_diag": comp_diag, "cd_diag": cd_diag,
            "fact": fact, "fd": fd, "reach": reach, "rd": rd,
        })
    return runs


def _failures(runs, predicate, describe):
    out = []
    for r in runs:
        if not predicate(r):
            out.append(f"{r['tid']}: {describe(r)}")
    return out


